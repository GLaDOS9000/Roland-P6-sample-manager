def test_write_and_read_preset_manifest(tmp_path):
    data = {
        "format_version": 3,
        "banks": {"A": {"pads": {"1": {"filepath": "BANK_A/PAD_1/kick.wav"}}}},
    }
    write_preset_manifest(str(tmp_path), data)
    result = read_preset_manifest(str(tmp_path))
    assert result == data


