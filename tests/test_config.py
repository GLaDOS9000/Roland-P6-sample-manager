def test_safe_base_name_plain():
    assert safe_base_name("/path/to/my_file.wav") == "my_file"


def test_safe_base_name_no_extension():
    assert safe_base_name("/path/to/my_file") == "my_file"


def test_safe_base_name_unicode_accent():
    # é decomposes to e + combining acute via NFKD; the combining mark is
    # then dropped by the ASCII encode step.
    assert safe_base_name("café.wav") == "cafe"


def test_safe_base_name_transliterate_german():
    assert safe_base_name("Straße.wav") == "Strasse"


def test_safe_base_name_transliterate_nordic():
    # ø transliterates to "oe" per _TRANSLITERATE, so "møøse" → "moeoese"
    assert safe_base_name("møøse.wav") == "moeoese"


def test_safe_base_name_reserved_windows_name():
    # FAT/Windows device names must not be used as filenames.
    assert safe_base_name("CON.wav") == "CON_"
    assert safe_base_name("NUL.wav") == "NUL_"
    assert safe_base_name("COM1.wav") == "COM1_"
    assert safe_base_name("LPT9.wav") == "LPT9_"


def test_safe_base_name_reserved_is_case_insensitive():
    # The check is against the uppercased form.
    assert safe_base_name("con.wav") == "con_"


def test_safe_base_name_max_len():
    long_name = "a" * 100 + ".wav"
    result = safe_base_name(long_name)
    assert len(result) <= 48


def test_safe_base_name_custom_max_len():
    result = safe_base_name("abcdefghij.wav", max_len=5)
    assert len(result) <= 5


def test_safe_base_name_fat_forbidden_chars():
    # Characters FAT rejects should be replaced with underscores.
    result = safe_base_name('file<>:"/\\|?*.wav')
    for ch in '<>:"/\\|?*':
        assert ch not in result


def test_safe_base_name_leading_dot_dropped():
    # Hidden files on Unix (.hidden) must not reach the FAT drive.
    result = safe_base_name(".hidden.wav")
    assert not result.startswith(".")


def test_safe_base_name_empty_returns_fallback():
    assert safe_base_name("") == "sample"
    assert safe_base_name(None) == "sample"


def test_safe_base_name_custom_fallback():
    assert safe_base_name("", fallback="untitled") == "untitled"


def test_safe_base_name_strip_tags_trim():
    # _trim_<bank><pad>_<hex> is the pattern generated by derived_temp_path.
    result = safe_base_name("kick_trim_A1_deadbeef.wav", strip_tags=True)
    assert result == "kick"


def test_safe_base_name_strip_tags_chop():
    result = safe_base_name("loop_chop_cafe1234.wav", strip_tags=True)
    assert result == "loop"


def test_safe_base_name_strip_tags_idempotent():
    # A name with no temp tag should not change.
    result = safe_base_name("snare.wav", strip_tags=True)
    assert result == "snare"


def test_safe_base_name_no_strip_tags_by_default():
    # Without strip_tags the suffix is kept.
    result = safe_base_name("kick_trim_deadbeef.wav")
    assert "trim" in result


