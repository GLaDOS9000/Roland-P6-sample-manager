def test_add_recent_preset_first_entry(isolated_config):
    add_recent_preset("/presets/my_kit")
    assert load_recent_presets() == ["/presets/my_kit"]


def test_add_recent_preset_most_recent_first(isolated_config):
    add_recent_preset("/presets/a")
    add_recent_preset("/presets/b")
    recents = load_recent_presets()
    assert recents[0] == "/presets/b"
    assert recents[1] == "/presets/a"


def test_add_recent_preset_deduplication(isolated_config):
    add_recent_preset("/presets/a")
    add_recent_preset("/presets/b")
    add_recent_preset("/presets/a")  # re-add: should move to front, not duplicate
    recents = load_recent_presets()
    assert recents == ["/presets/a", "/presets/b"]


def test_add_recent_preset_capped_at_five(isolated_config):
    for i in range(7):
        add_recent_preset(f"/presets/{i}")
    recents = load_recent_presets()
    assert len(recents) == 5
    assert recents[0] == "/presets/6"  # most recent


