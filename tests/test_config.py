@pytest.fixture
def isolated_lib(tmp_path, monkeypatch):
    lib_file = str(tmp_path / "waveforms.json")
    monkeypatch.setattr("pyp6.config.WAVEFORM_LIB_FILE", lib_file)
    monkeypatch.setattr("pyp6.config.APP_DIR", str(tmp_path))
    return tmp_path


def test_load_drawn_library_empty(isolated_lib):
    assert load_drawn_library() == {}


def test_save_and_load_drawn_library(isolated_lib):
    library = {
        "MyWave": {
            "kind": "draw",
            "name": "MyWave",
            "a": [0.0, 1.0, 0.0, -1.0, 0.0],
            "b": [0.0, 0.5, 0.0, -0.5, 0.0],
        }
    }
    assert save_drawn_library(library) is True
    loaded = load_drawn_library()
    assert "MyWave" in loaded
    assert loaded["MyWave"]["a"] == [0.0, 1.0, 0.0, -1.0, 0.0]


def test_save_drawn_library_filters_entries_without_shape(isolated_lib):
    """An entry with no 'a' data must not make it into the saved file."""
    library = {
        "Good": {"kind": "draw", "name": "Good", "a": [0.0, 1.0, 0.0], "b": []},
        "Bad": {"kind": "draw", "name": "Bad"},  # no 'a' key
    }
    save_drawn_library(library)
    loaded = load_drawn_library()
    assert "Good" in loaded
    # 'Bad' has no 'a' list — load_drawn_library skips it
    assert "Bad" not in loaded


def test_load_drawn_library_ignores_malformed_file(isolated_lib, monkeypatch):
    lib_path = str(isolated_lib / "waveforms.json")
    with open(lib_path, "w") as f:
        f.write("not json")
    assert load_drawn_library() == {}
